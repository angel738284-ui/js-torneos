import {readFileSync} from 'node:fs';
import {strict as assert} from 'node:assert';
import * as THREE from './bomba3d/vendor/three.module.js';
import {GLTFLoader} from './bomba3d/vendor/GLTFLoader.js';
const data=readFileSync(new URL('./bomba3d/models/js-rubber-animated.glb',import.meta.url));
const jlen=data.readUInt32LE(12),at=20+jlen,bin=data.subarray(at+8);
const g=JSON.parse(data.toString('utf8',20,at));
delete g.images;delete g.textures;delete g.samplers;
delete g.meshes[0].primitives[0].material;
const json=Buffer.from(JSON.stringify(g));
const padding=(4-json.length%4)%4;
const jsonChunk=Buffer.concat([json,Buffer.alloc(padding,32)]);
const glb=Buffer.alloc(12+8+jsonChunk.length+8+bin.length);
glb.write('glTF');glb.writeUInt32LE(2,4);glb.writeUInt32LE(glb.length,8);
glb.writeUInt32LE(jsonChunk.length,12);glb.write('JSON',16);jsonChunk.copy(glb,20);
const offset=20+jsonChunk.length;
glb.writeUInt32LE(bin.length,offset);glb.write('BIN\0',offset+4);bin.copy(glb,offset+8);
console.log('Loading texture-free runtime test GLB',glb.length);
const parsed=await new GLTFLoader().parseAsync(glb.buffer.slice(glb.byteOffset,glb.byteOffset+glb.byteLength),'');
assert.equal(parsed.animations.length,6);
let mesh;parsed.scene.traverse(o=>{if(o.isSkinnedMesh)mesh=o;});
assert.ok(mesh,'No SkinnedMesh generated by loader');
assert.equal(mesh.skeleton.bones.length,11);
const clone=parsed.scene.clone(true);
let cloneMesh;clone.traverse(o=>{if(o.isSkinnedMesh)cloneMesh=o;});
const bones=mesh.skeleton.bones.map(b=>clone.getObjectByName(b.name));
assert.ok(bones.every(Boolean));cloneMesh.bind(new THREE.Skeleton(bones,mesh.skeleton.boneInverses.map(m=>m.clone())),mesh.bindMatrix.clone());
assert.notEqual(mesh.skeleton.bones[0],cloneMesh.skeleton.bones[0]);
const mix=new THREE.AnimationMixer(clone);
for(const clip of parsed.animations){
 mix.stopAllAction();
 const action=mix.clipAction(clip).reset().play();
 mix.update(Math.min(.32,clip.duration*.4));
 const bone=clone.getObjectByName('Arm_L');
 assert.ok(Number.isFinite(bone.rotation.x));
 console.log('Runtime clip OK:',clip.name,'joint Arm_L rad:',bone.rotation.x.toFixed(3));
}
console.log('SUCCESS: GLTFLoader + AnimationMixer + independent Skeleton');
